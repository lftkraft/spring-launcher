import { writable, derived } from 'svelte/store';
import { invoke } from '@tauri-apps/api/core';

export type Language = 'en' | 'hu' | 'de';

export const currentLanguage = writable<Language>('en');

export function setLanguage(lang: Language) {
  currentLanguage.set(lang);
}

export async function initLanguage() {
  try {
    const settings: any = await invoke('get_settings');
    if (settings && settings.language) {
      const l = settings.language.toLowerCase();
      if (l === 'hu' || l === 'de' || l === 'en') {
        currentLanguage.set(l as Language);
        return;
      }
    }
  } catch (err) {
    console.error('Failed to init language from settings:', err);
  }
  currentLanguage.set('en');
}

export const t = derived(currentLanguage, ($lang) => {
  return (key: string, params?: Record<string, string | number>) => {
    const dict = (translations as any)[$lang] || translations.en;
    let val = dict[key] || (translations.en as any)[key] || key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        val = val.replace(`{${k}}`, String(v));
      }
    }
    return val;
  };
});

